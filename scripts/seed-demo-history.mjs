import assert from 'node:assert/strict';
import { config } from 'dotenv';
import { createClient } from '@supabase/supabase-js';
import { buildDemoHistory, DEMO_HISTORY_TAG } from '../lib/demoHistory.ts';
config({ quiet: true });
const userId = process.argv[2];
const expectedEmail = process.env.DEMO_TARGET_EMAIL?.toLowerCase();
assert.match(userId || '', /^[0-9a-f-]{36}$/i, 'Pass the verified account ID');
assert.ok(expectedEmail, 'Set DEMO_TARGET_EMAIL to the explicitly requested account');
assert.equal(new URL(process.env.VITE_SUPABASE_URL).hostname, 'awijrkxrhlisixufiukw.supabase.co');
const db = createClient(process.env.VITE_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY, { auth: { persistSession: false, autoRefreshToken: false } });
const checked = result => { if (result.error) throw new Error(result.error.message); return result.data; };
const user = checked(await db.auth.admin.getUserById(userId)).user;
assert.equal(user.email?.toLowerCase(), expectedEmail, 'Only the requested account may receive fixtures');
const settings = checked(await db.from('user_settings').select('last_period_start').eq('user_id', userId).single());
assert.ok(settings.last_period_start, 'Keep the account\'s established cycle anchor');
const previous = checked(await db.from('daily_logs').select('*').eq('user_id', userId).order('date'));
const rows = buildDemoHistory(userId, settings.last_period_start, 240);
const inserted = checked(await db.from('daily_logs').upsert(rows, { onConflict: 'user_id,date', ignoreDuplicates: true }).select('date'));
const after = checked(await db.from('daily_logs').select('*').eq('user_id', userId).order('date'));
for (const row of previous) assert.deepEqual(after.find(item => item.id === row.id), row, 'An existing check-in must remain unchanged');
assert.equal(checked(await db.from('user_settings').select('last_period_start').eq('user_id', userId).single()).last_period_start, settings.last_period_start);
console.log(JSON.stringify({ inserted: inserted.length, total: after.length, sampleRows: after.filter(row => row.notes?.startsWith(DEMO_HISTORY_TAG)).length, from: rows[0].date, through: rows.at(-1).date, existingLogsPreserved: previous.length, cycleSettingsUnchanged: true }));
