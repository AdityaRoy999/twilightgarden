// @vitest-environment jsdom
import React from 'react';
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
const mocks = vi.hoisted(() => ({ action: vi.fn(), signOut: vi.fn(), recover: vi.fn(), change: vi.fn(), accept: vi.fn(), rpc: vi.fn(), secret: vi.fn() }));
vi.mock('../contexts/AuthContext', () => ({ useAuth: () => ({ user: { id: 'owner' }, signOut: mocks.signOut }) }));
vi.mock('../contexts/VaultContext', () => ({ useVault: () => ({ epoch: 'epoch', recoverPassword: mocks.recover, changePassword: mocks.change, acceptDevice: mocks.accept }) }));
vi.mock('../lib/vaultRecovery', () => ({ vaultRecoveryAction: mocks.action }));
vi.mock('../lib/supabase', () => ({ rawSupabase: { rpc: mocks.rpc } }));
vi.mock('../lib/vaultTransfer', () => ({ newDeviceSecret: mocks.secret, deviceCodeHash: async () => 'a'.repeat(64), receiveVaultTransfer: vi.fn() }));
import { VaultRecoveryModal } from '../components/VaultRecoveryModal';
import { VaultPasswordModal } from '../components/VaultPasswordModal';
beforeEach(() => { vi.clearAllMocks(); mocks.action.mockResolvedValue({ sent: true }); mocks.recover.mockResolvedValue(undefined); mocks.rpc.mockResolvedValue({data:null,error:null}); mocks.secret.mockResolvedValue({code:'ABCDEFGHJKLMNPQR',publicKey:{},privateKey:{}}); });
afterEach(cleanup);
it('requires email verification and explicit deletion acknowledgement before resetting data', async () => {
  render(<VaultRecoveryModal open onClose={vi.fn()}/>);
  fireEvent.click(screen.getByRole('button', { name: 'No unlocked device? Reset encrypted data' }));
  expect(mocks.action).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole('button', { name: 'Send verification email' }));
  await screen.findByLabelText('Email verification code');
  expect(mocks.action).toHaveBeenCalledWith('send-code', 'epoch');
  const reset = screen.getByRole('button', { name: 'Permanently reset encrypted data' }) as HTMLButtonElement;
  expect(reset.disabled).toBe(true);
  fireEvent.change(screen.getByLabelText('Email verification code'), { target: { value: '123456' } });
  expect(reset.disabled).toBe(true);
  fireEvent.click(screen.getByRole('checkbox'));
  mocks.action.mockRejectedValueOnce(new Error('That email code is incorrect or expired.'));
  fireEvent.click(reset);
  expect(await screen.findByRole('alert')).toHaveProperty('textContent', 'That email code is incorrect or expired.');
  expect(mocks.signOut).not.toHaveBeenCalled();
  mocks.action.mockResolvedValueOnce({ reset: true });
  fireEvent.click(reset);
  await screen.findByRole('heading', { name: 'Encrypted data reset' });
  expect(mocks.action).toHaveBeenLastCalledWith('reset', 'epoch', '123456');
  fireEvent.click(screen.getByRole('button', { name: 'Return to sign in' }));
  expect(mocks.signOut).toHaveBeenCalledOnce();
});
it('lets an unlocked device replace a forgotten password without erasing data or requiring the old password', async () => {
  render(<VaultPasswordModal isOpen onClose={vi.fn()}/>);
  fireEvent.click(screen.getByRole('button', { name: 'I forgot my current password' }));
  expect(screen.queryByLabelText('Current backup password')).toBeNull();
  fireEvent.change(screen.getByLabelText('New backup password'), { target: { value: 'new-long-backup-password' } });
  fireEvent.change(screen.getByLabelText('Confirm new backup password'), { target: { value: 'new-long-backup-password' } });
  fireEvent.click(screen.getByRole('button', { name: 'Change backup password' }));
  await screen.findByRole('heading', { name: 'Backup password changed' });
  expect(mocks.recover).toHaveBeenCalledWith('new-long-backup-password');
  expect(mocks.change).not.toHaveBeenCalled();
  expect(mocks.action).not.toHaveBeenCalled();
});
it('shows the device code and cancels the request when recovery closes', async () => {
  const view = render(<VaultRecoveryModal open onClose={vi.fn()}/>);
  fireEvent.click(screen.getByRole('button', { name: 'Use an unlocked device' }));
  expect((await screen.findByLabelText('New device code')).textContent).toBe('ABCD EFGH JKLM NPQR');
  const call = mocks.rpc.mock.calls.find(([name]) => name === 'request_vault_device');
  expect(call?.[1].p_hash).toBe('a'.repeat(64));
  expect(JSON.stringify(call)).not.toContain('ABCDEFGHJKLMNPQR');
  view.unmount();
  expect(mocks.rpc).toHaveBeenCalledWith('cancel_vault_device', {p_id:call?.[1].p_id});
});
